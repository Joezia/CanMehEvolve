#!/usr/bin/env python3
"""Turn a greedy run's chain of CUMULATIVE patches into a sequentially applicable series of INCREMENTAL patches.

Every gen_N.patch the search saved is cumulative: it is the diff of the whole patched library against the stock SDK
(gen_N already contains every earlier accepted change). Applying them one after another would apply the same hunks
twice. This script instead applies each cumulative patch to a fresh copy of the stock sources, diffs it against the
previous accepted state, and commits only that difference. The series therefore applies in order with `git am` on
the stock sources and ends at exactly the final cumulative patch (checked by tree hash).

usage: make_patch_series.py <run_dir> <out_dir> [messages.json]
  messages.json: {"<generation>": {"subject": "...", "body": "..."}}; missing entries get a factual auto message.
Work happens under $SERIES_WORK (default ~/.deliver-work, NOT /tmp: /tmp has a 10 MB per-user quota here).
"""
import json, os, shutil, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STOCK = ROOT / "build" / "FITSDK-prefix" / "src" / "FITSDK" / "src"
WORK = Path(os.environ.get("SERIES_WORK", str(Path.home() / ".deliver-work")))
ENV = dict(os.environ, GIT_AUTHOR_NAME="CanMehEvolve", GIT_AUTHOR_EMAIL="noreply@example.com",
           GIT_COMMITTER_NAME="CanMehEvolve", GIT_COMMITTER_EMAIL="noreply@example.com",
           GIT_AUTHOR_DATE="2026-11-04T12:00:00+08:00", GIT_COMMITTER_DATE="2026-11-04T12:00:00+08:00")


def git(repo, *args, check=True, inp=None):
    return subprocess.run(["git", "-C", str(repo), *args], env=ENV, check=check, capture_output=True, text=True, input=inp)


def main():
    run, out = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
    msgs = json.load(open(sys.argv[3])) if len(sys.argv) > 3 else {}
    summ = json.load(open(run / "summary.json"))
    rows = {r["generation"]: r for r in (json.loads(l) for l in open(run / "results.jsonl") if l.strip())}
    ups = summ["rank_updates"]
    repo = WORK / ("series-" + run.name)
    shutil.rmtree(repo, ignore_errors=True)
    (repo / "src").parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(STOCK, repo / "src")
    git(repo, "init", "-q")
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", "stock FIT SDK 21.201.0 src/ (not redistributed; this repo is local scratch)")
    stock = git(repo, "rev-parse", "HEAD").stdout.strip()
    out.mkdir(parents=True, exist_ok=True)
    for f in out.glob("*.patch"):
        f.unlink()
    for n, u in enumerate(ups, 1):
        g = u["generation"]
        cum = Path(rows[g]["patch"]) if rows[g].get("patch") else run / "patches" / ("gen_%d.patch" % g)
        git(repo, "checkout", "-q", stock, "--", ".")
        git(repo, "clean", "-fdq")
        r = subprocess.run(["git", "-C", str(repo), "apply", str(cum)], capture_output=True, text=True)
        if r.returncode:
            sys.exit("cumulative patch %s does not apply to stock: %s" % (cum, r.stderr))
        git(repo, "add", "-A")
        m = msgs.get(str(g), {})
        subject = m.get("subject") or "%s: model rewrite accepted by the search (generation %d)" % (u["label"], g)
        prev = u["previous_R"]
        body = (m.get("body") or "").rstrip()
        body += ("\n\nProvenance: greedy search, seed %d, generation %d, region %d (%s).\n"
                 "Generated by the model (deepseek-v4.1-flash); not hand-written. Search-time ratio R (candidate/stock, <1 is faster): "
                 "%.4f -> %.4f at acceptance (max of two measurements). This is a ranking value, NOT an independent per-patch\n"
                 "confirmation; only the fixed FINAL patch of the run was re-measured independently.\n"
                 "Cumulative patch it was derived from: %s (diff against stock; do not apply together with the others).\n"
                 "Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>\n") % (
            summ["seed"], g, u["region"], u["label"], prev, u["R"], os.path.relpath(cum, ROOT))
        git(repo, "commit", "-q", "--allow-empty", "-F", "-", inp=subject + "\n\n" + body)
        git(repo, "format-patch", "-q", "-1", "--start-number", str(n), "-o", str(out))
    # verification: replay the series on a fresh stock copy and compare with the final cumulative patch
    chk = WORK / "verify"
    shutil.rmtree(chk, ignore_errors=True)
    shutil.copytree(STOCK, chk / "src")
    git(chk, "init", "-q"); git(chk, "add", "-A"); git(chk, "commit", "-q", "-m", "stock")
    series = sorted(out.glob("*.patch"))
    for p in series:
        r = subprocess.run(["git", "-C", str(chk), "am", "-q", str(p)], env=ENV, capture_output=True, text=True)
        if r.returncode:
            sys.exit("series does not apply in order at %s: %s" % (p.name, r.stderr))
    fin = WORK / "verify2"
    shutil.rmtree(fin, ignore_errors=True)
    shutil.copytree(STOCK, fin / "src")
    git(fin, "init", "-q"); git(fin, "add", "-A"); git(fin, "commit", "-q", "-m", "stock")
    last_cum = run / "patches" / ("gen_%d.patch" % ups[-1]["generation"])
    git(fin, "apply", str(last_cum)); git(fin, "add", "-A"); git(fin, "commit", "-q", "-m", "final cumulative")
    same = git(chk, "rev-parse", "HEAD^{tree}").stdout == git(fin, "rev-parse", "HEAD^{tree}").stdout
    print("series of %d patches in %s; replay == final cumulative patch tree: %s" % (len(series), out, same))
    if not same:
        sys.exit(2)


if __name__ == "__main__":
    main()
